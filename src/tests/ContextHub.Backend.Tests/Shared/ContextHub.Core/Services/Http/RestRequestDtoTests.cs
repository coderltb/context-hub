namespace ContextHub.Backend.Tests.Shared.ContextHub.Core.Services.Http;

/// <summary>
/// Exercises DTO-based REST calls through DI without mutating caller data or sharing credentials.
/// </summary>
[Collection(nameof(GlobalMappingCollection))]
public sealed class RestRequestDtoTests
{
    /// <summary>
    /// Selects native form content by parsed media type, including case variations and valid parameters.
    /// </summary>
    /// <param name="contentType">The caller's parameterized content type.</param>
    /// <param name="multipart">Whether fields and an upload must be sent as native multipart content.</param>
    /// <returns>The asynchronous assertions against the actual outbound body.</returns>
    [Theory]
    [InlineData("Application/X-Www-Form-Urlencoded; charset=utf-8", false)]
    [InlineData("application/x-www-form-urlencoded; charset=utf-8", false)]
    [InlineData("Multipart/Form-Data; boundary=caller-boundary", true)]
    [InlineData("multipart/form-data; charset=utf-8", true)]
    public async Task ParameterizedMediaType_PreservesFormFieldsAndUploads(string contentType, bool multipart)
    {
        string? body = null;
        MediaTypeHeaderValue? observedType = null;
        var services = new ServiceCollection().AddLogging();
        services.AddHttpClientInfrastructure("form-probe", _ => { })
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler(async (request, token) =>
            {
                body = await request.Content!.ReadAsStringAsync(token);
                observedType = request.Content.Headers.ContentType;

                return new HttpResponseMessage(HttpStatusCode.OK);
            }));
        using var provider = services.BuildServiceProvider();
        using var upload = new StringContent("upload-payload");
        var dto = new BaseHttpRequest
        {
            HttpClientName = "form-probe", RequestUri = "https://selected.invalid/items",
            ContentType = contentType,
            RequestFormData = new Dictionary<string, string> { ["name"] = "a b&c" },
            File = multipart ? upload : null,
            FileName = "sample.txt"
        };

        using var response = await provider.GetRequiredService<IRestClientMultipleService>().PostAsync(dto);

        Assert.Equal(contentType, dto.ContentType);
        Assert.Equal(multipart ? "multipart/form-data" : "application/x-www-form-urlencoded", observedType!.MediaType);
        if (multipart)
        {
            // The boundary must describe the bytes generated by native multipart content, not caller-supplied text.
            var boundary = observedType.Parameters.Single(parameter => parameter.Name == "boundary").Value!.Trim('"');
            Assert.NotEqual("caller-boundary", boundary);
            Assert.Contains("--" + boundary, body);
            Assert.Contains("a b&c", body);
            Assert.Contains("upload-payload", body);
            await Assert.ThrowsAsync<ObjectDisposedException>(() => upload.ReadAsStringAsync());
        }
        else
        {
            Assert.Equal("name=a+b%26c", body);
        }
    }

    /// <summary>
    /// Preserves valid parameters for ordinary content rather than normalizing away provider-specific metadata.
    /// </summary>
    /// <returns>The asynchronous payload and content-type assertions.</returns>
    [Fact]
    public async Task OrdinaryPayload_RetainsMediaTypeParameters()
    {
        const string contentType = "application/json; charset=utf-8; profile=\"urn:example\"";
        string? observedType = null;
        string? body = null;
        var services = new ServiceCollection().AddLogging();
        services.AddHttpClientInfrastructure("payload-probe", _ => { })
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler(async (request, token) =>
            {
                observedType = request.Content!.Headers.ContentType!.ToString();
                body = await request.Content.ReadAsStringAsync(token);

                return new HttpResponseMessage(HttpStatusCode.OK);
            }));
        using var provider = services.BuildServiceProvider();
        var dto = new BaseHttpRequest
        {
            HttpClientName = "payload-probe", RequestUri = "https://selected.invalid/items",
            ContentType = contentType, RequestData = "{\"name\":\"sample\"}"
        };

        using var response = await provider.GetRequiredService<IRestClientMultipleService>().PostAsync(dto);

        Assert.Equal(contentType, observedType);
        Assert.Equal(dto.RequestData, body);
    }

    /// <summary>
    /// Retains DTO stream ownership when invalid content configuration fails before HTTP dispatch.
    /// </summary>
    /// <returns>The asynchronous construction-failure and cleanup assertions.</returns>
    [Fact]
    public async Task InvalidMediaType_DisposesTransferredStreamWithoutDispatch()
    {
        var services = new ServiceCollection().AddLogging();
        services.AddHttpClientInfrastructure("payload-probe", _ => { })
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler((_, _) =>
                throw new InvalidOperationException("HTTP must not run for invalid content configuration.")));
        using var provider = services.BuildServiceProvider();
        using var stream = new MemoryStream([1, 2, 3]);
        var dto = new BaseHttpRequest
        {
            HttpClientName = "payload-probe", RequestUri = "https://selected.invalid/items",
            ContentType = "not a media type", RequestStream = stream
        };

        await Assert.ThrowsAsync<FormatException>(() => provider.GetRequiredService<IRestClientMultipleService>().PostAsync(dto));

        Assert.False(stream.CanRead);
    }

    /// <summary>
    /// Preserves native disposal semantics when releasing a transferred stream also fails during construction cleanup.
    /// </summary>
    /// <returns>The asynchronous native cleanup failure and disposal assertions.</returns>
    [Fact]
    public async Task InvalidMediaType_DisposeFailurePropagatesNatively()
    {
        var logger = new TestLogger<RestClientMultipleService>();
        var services = new ServiceCollection().AddLogging().AddRestClients();
        services.AddSingleton<ILogger<RestClientMultipleService>>(logger);
        using var provider = services.BuildServiceProvider();
        var stream = new ThrowingDisposeStream();
        var dto = new BaseHttpRequest
        {
            HttpClientName = "payload-probe", RequestUri = "https://selected.invalid/items",
            ContentType = "not a media type", RequestStream = stream
        };

        await Assert.ThrowsAsync<IOException>(() =>
            provider.GetRequiredService<IRestClientMultipleService>().PostAsync(dto));

        Assert.Equal(1, stream.DisposeCalls);
        Assert.False(stream.CanRead);
        Assert.DoesNotContain(logger.Entries, entry => entry.Level >= LogLevel.Warning);
    }

    /// <summary>
    /// Injects only a disposal failure while retaining the native stream lifecycle.
    /// </summary>
    private sealed class ThrowingDisposeStream : MemoryStream
    {
        /// <summary>
        /// Counts explicit release attempts without faulting from finalization.
        /// </summary>
        public int DisposeCalls { get; private set; }

        /// <summary>
        /// Releases the stream, then faults only explicit disposal to exercise primary-error preservation.
        /// </summary>
        /// <param name="disposing">Whether this is an explicit resource release.</param>
        protected override void Dispose(bool disposing)
        {
            base.Dispose(disposing);
            if (disposing)
            {
                DisposeCalls++;
                throw new IOException("private-cleanup-message");
            }
        }
    }

    /// <summary>
    /// Honors Newtonsoft property attributes through the retained DTO facade and named REST transport.
    /// </summary>
    /// <returns>A task that completes after the scenario's operations and assertions have finished.</returns>
    [Fact]
    public async Task RestJson_UsesInjectedNewtonsoftContract()
    {
        string? body = null;
        var services = new ServiceCollection().AddLogging().AddMapping();
        services.AddHttpClientInfrastructure("single", _ => { })
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler(async (request, token) =>
            {
                body = request.Content is null ? body : await request.Content.ReadAsStringAsync(token);

                return new HttpResponseMessage(HttpStatusCode.OK)
                {
                    Content = new StringContent("{\"wire_value\":\"returned\"}")
                };
            }));
        using var provider = services.BuildServiceProvider();
        using var scope = provider.CreateScope();
        var service = scope.ServiceProvider.GetRequiredService<IThirdPartyApiService>();
        var serializer = scope.ServiceProvider.GetRequiredService<IJsonSerializerService>();

        // The facade owns typed interpretation; the named transport still sends the actual provider request.
        var request = new BaseThirdPartyApiRequest
        {
            HttpClientName = "single",
            Endpoint = "https://selected.invalid",
            Method = "POST",
            Content = serializer.Serialize(new WirePayload { Value = "sent" })
        };

        var result = await service.HandleApiData<BaseThirdPartyApiRequest, WirePayload>(request);

        Assert.Equal("{\"wire_value\":\"sent\"}", body);
        Assert.Equal("returned", result!.Value);
    }

    /// <summary>
    /// Checks that parallel DTO calls through one named configuration never share credentials or mutate its base address.
    /// </summary>
    /// <returns>A task that completes after the scenario's operations and assertions have finished.</returns>
    [Fact]
    public async Task DtoCredentials_RemainRequestLocalOnNamedClient()
    {
        var observed = new ConcurrentBag<string>();
        var services = new ServiceCollection().AddLogging();
        services.AddHttpClientInfrastructure("single", client =>
                client.BaseAddress = new Uri("https://configured.invalid/"))
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler(async (request, _) =>
            {
                await Task.Yield();
                observed.Add(request.Headers.Authorization!.Parameter + "@" + request.RequestUri!.Host);

                return new HttpResponseMessage(HttpStatusCode.OK);
            }));
        using var provider = services.BuildServiceProvider();
        var service = provider.GetRequiredService<IRestClientMultipleService>();

        var responses = await Task.WhenAll(
            service.GetAsync(new BaseHttpRequest
            {
                HttpClientName = "single", RequestUri = "item", BaseAddress = "https://override.invalid/",
                AuthenticationValue = new AuthenticationHeaderValue("Bearer", "first")
            }),
            service.GetAsync(new BaseHttpRequest
            {
                HttpClientName = "single", RequestUri = "item",
                AuthenticationValue = new AuthenticationHeaderValue("Bearer", "second")
            }));

        Assert.Contains("first@override.invalid", observed);
        Assert.Contains("second@configured.invalid", observed);
        foreach (var response in responses)
        {
            response.Dispose();
        }
    }

    /// <summary>
    /// Provides a JSON attribute that distinguishes Newtonsoft from the framework serializer.
    /// </summary>
    public sealed class WirePayload
    {
        /// <summary>
        /// Gets or sets the externally named wire value.
        /// </summary>
        [Newtonsoft.Json.JsonProperty("wire_value")]
        public string? Value { get; set; }
    }

    /// <summary>
    /// Sends each DTO verb with encoded query and per-request authentication while preserving upstream failures.
    /// </summary>
    /// <param name="method">The HTTP verb used to dispatch this request.</param>
    /// <returns>A task that completes after the scenario's operations and assertions have finished.</returns>
    [Theory]
    [InlineData("GET")]
    [InlineData("POST")]
    [InlineData("PUT")]
    [InlineData("PATCH")]
    [InlineData("DELETE")]
    public async Task NamedDto_UsesRequestFieldsWithoutMutation(string method)
    {
        string? uri = null;
        string? authorization = null;
        string? body = null;
        var services = new ServiceCollection().AddLogging();
        services.AddHttpClientInfrastructure("upstream", client => client.BaseAddress = new Uri("https://unused.invalid"))
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler(async (request, token) =>
            {
                uri = request.RequestUri!.AbsoluteUri;
                authorization = request.Headers.Authorization?.ToString();
                body = request.Content is null ? null : await request.Content.ReadAsStringAsync(token);

                return new HttpResponseMessage(HttpStatusCode.Conflict);
            }));
        using var provider = services.BuildServiceProvider();
        var service = provider.GetRequiredService<IRestClientMultipleService>();
        var dto = new BaseHttpRequest
        {
            HttpClientName = "upstream",
            BaseAddress = "https://selected.invalid/api/",
            RequestUri = "items?existing=1#section",
            AdditionalQueryParams = new Dictionary<string, string> { ["q"] = "a b&c" },
            AuthenticationValue = new AuthenticationHeaderValue("Bearer", "private-token"),
            RequestData = "{\"name\":\"sample\"}"
        };

        using var response = await (method switch
        {
            "GET" => service.GetAsync(dto),
            "POST" => service.PostAsync(dto),
            "PUT" => service.PutAsync(dto),
            "PATCH" => service.PatchAsync(dto),
            _ => service.DeleteAsync(dto)
        });

        Assert.Equal(HttpStatusCode.Conflict, response.StatusCode);
        Assert.Equal("https://selected.invalid/api/items?existing=1&q=a%20b%26c#section", uri);
        Assert.Equal("Bearer private-token", authorization);
        Assert.Equal("items?existing=1#section", dto.RequestUri);
        Assert.Equal(method is "GET" or "DELETE" ? null : dto.RequestData, body);
    }

    /// <summary>
    /// Disposes DTO upload resources with their native request; each DTO upload is a one-send payload.
    /// </summary>
    /// <param name="kind">The request content variant selected by this scenario.</param>
    /// <returns>A task that completes after the scenario's operations and assertions have finished.</returns>
    [Theory]
    [InlineData("stream")]
    [InlineData("form")]
    [InlineData("multipart")]
    public async Task DtoContent_IsDisposedByTransport(string kind)
    {
        string? body = null;
        string? mediaType = null;
        var services = new ServiceCollection().AddLogging();
        services.AddHttpClientInfrastructure("single", _ => { })
            .ConfigurePrimaryHttpMessageHandler(() => new BoundaryHandler(async (request, token) =>
            {
                body = await request.Content!.ReadAsStringAsync(token);
                mediaType = request.Content.Headers.ContentType!.MediaType;

                return new HttpResponseMessage(HttpStatusCode.OK);
            }));
        using var provider = services.BuildServiceProvider();
        var service = provider.GetRequiredService<IRestClientMultipleService>();
        using var stream = new MemoryStream(Encoding.UTF8.GetBytes("sample"));
        using var file = new StringContent("sample");
        var dto = new BaseHttpRequest
        {
            HttpClientName = "single", RequestUri = "https://selected.invalid/items",
            ContentType = kind switch
            {
                "form" => "application/x-www-form-urlencoded",
                "multipart" => "multipart/form-data",
                _ => "application/octet-stream"
            },
            RequestStream = kind == "stream" ? stream : null,
            RequestFormData = new Dictionary<string, string> { ["name"] = "sample" },
            File = kind == "multipart" ? file : null,
            FileName = "sample.txt"
        };

        using var response = await service.PostAsync(dto);

        Assert.Contains("sample", body);
        Assert.Equal(dto.ContentType, mediaType);
        Assert.Equal(kind != "stream", stream.CanRead);
        if (kind == "multipart")
        {
            await Assert.ThrowsAsync<ObjectDisposedException>(() => file.ReadAsStringAsync());
        }
    }

    /// <summary>
    /// Substitutes only the upstream boundary while retaining real DI and the shared transport.
    /// </summary>
    /// <param name="send">The synthetic upstream invoked with the real outgoing request and cancellation token.</param>
    private sealed class BoundaryHandler(Func<HttpRequestMessage, CancellationToken, Task<HttpResponseMessage>> send) : HttpMessageHandler
    {
        /// <summary>
        /// Observes the request produced by the shared DTO adapter.
        /// </summary>
        /// <param name="request">The native request sent through the configured HTTP handler pipeline.</param>
        /// <param name="cancellationToken">Cancellation propagated to the underlying operation.</param>
        /// <returns>The actual unread upstream response; the receiving caller must consume and dispose it.</returns>
        protected override Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken) =>
            send(request, cancellationToken);
    }
}
